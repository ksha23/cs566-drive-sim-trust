"""DL3DV validation tables (results/dl3dv/summary.md, summary.csv) from val_metrics.py outputs:
results/dl3dv/test_s{30,60}.json (set-level means + FID/KID) and test_s{30,60}_rows.json (per image).
Per level and model: mean PSNR/SSIM/LPIPS with 95% bootstrap CIs over images, FID/KID over the set, per-scene LPIPS;
paired differences (same images) of our matched run vs. the official matched run, and of each model vs. the raw render.
usage: scripts/lib/py.sh src/dl3dv/summarize.py
"""
import json
import numpy as np
import pandas as pd

R = "results/dl3dv"
NAMES = {"raw": "raw sparse-view render", "released": "released Difix (nvidia/difix)",
         "released_ref": "released Difix-ref (nvidia/difix_ref)",
         "official448": "official trainer, matched (no ref, 448x768, 1,801 steps)",
         "ours448": "our trainer, matched (no ref, 448x768, 1,801 steps)",
         "oursref": "our trainer, ref view, 576x1024 (1,801 steps, val-selected step 1,200)"}
rng = np.random.default_rng(0)


def ci(v, n=4000):
    v = np.asarray(v, float); idx = rng.integers(0, len(v), (n, len(v))); m = v[idx].mean(1)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def main():
    out, recs, prs = ["# DL3DV validation of our Difix reimplementation\n",
                      "Generated by `src/dl3dv/summarize.py` from `results/dl3dv/test_s*.json` and `test_s*_rows.json`. "
                      "Held-out TEST scenes: 5c3af581, 9c8c0e0f, cc08c0bd (DL3DV-10K sample). S = the splat was fitted on "
                      "every S-th video frame; images = every 3rd held-out frame. CIs: 95% bootstrap over images.\n"], [], []
    for L in (30, 60):
        S = json.load(open(f"{R}/test_s{L}.json")); df = pd.DataFrame(json.load(open(f"{R}/test_s{L}_rows.json")))
        df["sc"] = df.scene.str[:8]; scenes = sorted(df.sc.unique())
        out += [f"## S = {L}\n", "| model | n | PSNR↑ [CI] | SSIM↑ | LPIPS↓ [CI] | FID↓ | KID↓ | LPIPS per scene (" + ", ".join(scenes) + ") |",
                "|---|---|---|---|---|---|---|---|"]
        for m in NAMES:
            g = df[df.method == m]
            if not len(g):
                continue
            p, l = ci(g.psnr), ci(g.lpips)
            per = ", ".join(f"{g[g.sc == s].lpips.mean():.3f}" for s in scenes)
            recs.append(dict(level=L, method=m, n=len(g), psnr=g.psnr.mean(), psnr_lo=p[0], psnr_hi=p[1], ssim=g.ssim.mean(),
                             lpips=g.lpips.mean(), lpips_lo=l[0], lpips_hi=l[1], fid=S[m]["fid"], kid=S[m]["kid"],
                             **{f"lpips_{s}": g[g.sc == s].lpips.mean() for s in scenes}))
            out.append(f"| {NAMES[m]} | {len(g)} | {g.psnr.mean():.2f} [{p[0]:.2f}, {p[1]:.2f}] | {g.ssim.mean():.3f} | "
                       f"{g.lpips.mean():.3f} [{l[0]:.3f}, {l[1]:.3f}] | {S[m]['fid']:.1f} | {S[m]['kid']:.4f} | {per} |")
        out += ["", "Paired differences on the same images (A − B, mean [95% CI]; LPIPS: negative = A better):", "",
                "| A | B | ΔPSNR | ΔLPIPS | LPIPS: A better on (images / scenes) |", "|---|---|---|---|---|"]
        W = df.pivot_table(index="key", columns="method", values=["psnr", "lpips"]); sc = df.groupby("key").sc.first()
        for a, b in [("ours448", "official448"), ("oursref", "released_ref"), ("oursref", "ours448"), ("ours448", "raw"),
                     ("official448", "raw"), ("oursref", "raw"), ("released", "raw"), ("released_ref", "raw")]:
            dp = (W["psnr"][a] - W["psnr"][b]).values; dl = (W["lpips"][a] - W["lpips"][b]).values
            cp, cl = ci(dp), ci(dl)
            ns = sum((W["lpips"][a] - W["lpips"][b])[sc == s].mean() < 0 for s in scenes)
            prs.append(dict(level=L, a=a, b=b, dpsnr=dp.mean(), dpsnr_lo=cp[0], dpsnr_hi=cp[1], dlpips=dl.mean(),
                            dlpips_lo=cl[0], dlpips_hi=cl[1], frac_a_better=float((dl < 0).mean()), scenes_a_better=int(ns)))
            out.append(f"| {a} | {b} | {dp.mean():+.2f} [{cp[0]:+.2f}, {cp[1]:+.2f}] | {dl.mean():+.3f} [{cl[0]:+.3f}, {cl[1]:+.3f}] | "
                       f"{(dl < 0).mean():.0%} / {ns} of {len(scenes)} |")
        out.append("")
    pd.DataFrame(recs).to_csv(f"{R}/summary.csv", index=False); pd.DataFrame(prs).to_csv(f"{R}/paired.csv", index=False)
    open(f"{R}/summary.md", "w").write("\n".join(out) + "\n"); print("\n".join(out))


if __name__ == "__main__":
    main()
